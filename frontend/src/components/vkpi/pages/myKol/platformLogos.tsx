export const platformBrandColor = (platform: string) => PLATFORM_BRAND_COLOR[platform.toLowerCase()] || '#8b5cf6';

export function PlatformLogo({ platform, size = 24 }: { platform: string; size?: number }) {
  const key = platform.toLowerCase();
  const renderer = PLATFORM_LOGOS[key];
  if (renderer) return renderer(size);
  // 未知平台:用首字母兜底,保持原 letter-badge 行为不破。
  return (
    <span style={{ fontWeight: 850, fontSize: size * 0.55, lineHeight: 1 }}>
      {(platform.slice(0, 1) || '?').toUpperCase()}
    </span>
  );
}
