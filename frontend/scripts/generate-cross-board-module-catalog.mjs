import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(scriptDir, "..");
const pagesDir = path.join(frontendRoot, "src/components/vkpi/cockpit/pages");
const outputPath = path.join(pagesDir, "crossBoardModules.catalog.generated.ts");

const sources = [
  ["MyKolBoardPage.tsx", "my-kol", "MY KOL"],
  ["KolPoolBoardPage.tsx", "kol-pool", "KOL Pool"],
  ["KolProfileBoardPage.tsx", "kolProfile", "KOL 档案"],
  ["ProjectsBoardPage.tsx", "projects", "Projects"],
  ["EventsBoardPage.tsx", "events", "Events"],
  ["ShopifyBoardPage.tsx", "shopify", "Shopify"],
  ["DealersBoardPage.tsx", "dealers", "Dealers"],
  ["IntelligentBoardPage.tsx", "intelligent", "Intelligent 问答"],
  ["MarketVoicePage.tsx", "marketVoice", "市场之声"],
  ["Sku360BoardPage.tsx", "sku360", "SKU 360°"],
  ["CreativeLibraryBoardPage.tsx", "creativeLibrary", "创意资产库"],
  ["ReplyQueueBoardPage.tsx", "replyQueue", "回复队列"],
  ["LaunchPadBoardPage.tsx", "launchpad", "发射台"],
  ["AutonomyDrivePage.tsx", "autonomy", "自治驾照"],
  ["StrategyDeskPage.tsx", "strategyBoard", "战略台"],
  ["GtmCommandBoardPage.tsx", "gtmCommand", "GTM Command"],
  // Ops pages predate the editable-board registry. Keep one honest whole-page
  // module for each until they expose smaller DashboardModuleDefinition parts.
  ["../../pages/DataQualityPage.tsx", "triage", "运维 Triage", [
    { moduleKey: "overview", label: "数据质量与失败队列", defaultSpan: 12, minSpan: 6, defaultHeight: 20, minHeight: 10, maxHeight: 44 },
  ]],
  ["../../pages/DataQueryPage.tsx", "dataQuery", "问数", [
    { moduleKey: "overview", label: "问数与数据导出", defaultSpan: 12, minSpan: 6, defaultHeight: 20, minHeight: 10, maxHeight: 44 },
  ]],
  ["../../pages/MarketTrendsPage.tsx", "marketTrends", "市场趋势", [
    { moduleKey: "overview", label: "市场趋势观察", defaultSpan: 12, minSpan: 6, defaultHeight: 20, minHeight: 10, maxHeight: 44 },
  ]],
  ["../../pages/SkillStudioPage.tsx", "skillStudio", "Skill Studio", [
    { moduleKey: "overview", label: "Skill Studio", defaultSpan: 12, minSpan: 6, defaultHeight: 20, minHeight: 10, maxHeight: 44 },
  ]],
];

const objectPattern = /\{\s*key:\s*"([^"]+)",\s*label:\s*"([^"]+)",\s*description:\s*"([^"]+)",\s*category:\s*"([^"]+)",\s*defaultSpan:\s*(\d+)(.*?)(?:render:)/gs;
const numberFrom = (tail, name, fallback) => {
  const match = tail.match(new RegExp(`${name}:\\s*(\\d+)`));
  return match ? Number(match[1]) : fallback;
};

const groups = [];
for (const [fileName, board, boardLabel, fallbackModules = []] of sources) {
  const source = fs.readFileSync(path.join(pagesDir, fileName), "utf8").replace(/^\s*\/\/.*$/gm, "");
  const modules = [];
  for (const match of source.matchAll(objectPattern)) {
    const [, moduleKey, label, description, , defaultSpanText, tail] = match;
    modules.push({
      moduleKey,
      label,
      defaultSpan: Number(defaultSpanText),
      minSpan: numberFrom(tail, "minSpan", 3),
      defaultHeight: numberFrom(tail, "defaultHeight", 9),
      minHeight: numberFrom(tail, "minHeight", 4),
      maxHeight: numberFrom(tail, "maxHeight", 36),
    });
  }
  if (modules.length === 0 && fallbackModules.length > 0) modules.push(...fallbackModules);
  groups.push({ board, boardLabel, modules });
}

const escape = (value) => JSON.stringify(value, null, 0);
const body = groups.map((group) => {
  const modules = group.modules.map((row) => (
    `      { moduleKey: ${escape(row.moduleKey)}, label: ${escape(row.label)}, defaultSpan: ${row.defaultSpan}, minSpan: ${row.minSpan}, defaultHeight: ${row.defaultHeight}, minHeight: ${row.minHeight}, maxHeight: ${row.maxHeight} },`
  )).join("\n");
  return `  {\n    board: ${escape(group.board)},\n    boardLabel: ${escape(group.boardLabel)},\n    modules: [\n${modules}\n    ],\n  },`;
}).join("\n");

const output = `// AUTO-GENERATED by frontend/scripts/generate-cross-board-module-catalog.mjs.
// Source of truth is each board page's DashboardModuleDefinition registry.
// Run: node scripts/generate-cross-board-module-catalog.mjs

export interface FullBoardModuleMeta {
  moduleKey: string;
  label: string;
  defaultSpan: number;
  minSpan: number;
  defaultHeight: number;
  minHeight: number;
  maxHeight: number;
}

export interface FullBoardModuleSource {
  board: string;
  boardLabel: string;
  modules: FullBoardModuleMeta[];
}

export const FULL_BOARD_MODULE_CATALOG: FullBoardModuleSource[] = [
${body}
];
`;

const totalModules = groups.reduce((total, group) => total + group.modules.length, 0);
if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    process.stderr.write("cross-board module catalog is stale; run npm run generate:cross-board-catalog\n");
    process.exitCode = 1;
  } else {
    process.stdout.write(`cross-board catalog current (${totalModules} modules)\n`);
  }
} else {
  fs.writeFileSync(outputPath, output, "utf8");
  process.stdout.write(`generated ${totalModules} modules -> ${path.relative(frontendRoot, outputPath)}\n`);
}
