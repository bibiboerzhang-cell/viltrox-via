def _backend_operation_status(backend: Any) -> dict[str, Any]:
    get_status = getattr(backend, "operation_status", None)
    if not callable(get_status):
        return {"ready": False, "error": "vector backend status unavailable"}
    try:
        status = get_status()
    except Exception as exc:  # noqa: BLE001
        return {"ready": False, "error": _operation_error("vector_backend_status", exc)}
    if not isinstance(status, dict):
        return {"ready": False, "error": "vector backend returned invalid status"}
    return {
        "ready": bool(status.get("ready")),
        "error": str(status.get("error") or ""),
    }


def _vector_write_status(backend: Any, *, requested: int, upserted: int) -> dict[str, Any]:
    backend_status = _backend_operation_status(backend)
    if requested <= 0:
        return {**backend_status, "status": "skipped", "reason": "no_documents"}
    if upserted == requested and backend_status["ready"]:
        return {**backend_status, "status": "ready", "reason": ""}
    reason = backend_status["error"] or (
        "partial_upsert" if 0 < upserted < requested else "vector_backend_unavailable"
    )
    return {**backend_status, "status": "partial", "reason": str(reason)[:300]}


def build_via_vector_backend() -> Any:
    global _vector_backend_singleton
    if _vector_backend_singleton is not None:
        return _vector_backend_singleton
    if VIA_VECTOR_BACKEND == "qdrant":
        _vector_backend_singleton = _QdrantVectorBackend()
    elif VIA_VECTOR_BACKEND == "weaviate":
        _vector_backend_singleton = _WeaviateVectorBackend()
    else:
        _vector_backend_singleton = _NullVectorBackend()
    return _vector_backend_singleton


async def sync_bundle_memory_refs_to_vector(bundle: dict[str, Any]) -> dict[str, Any]:
    backend = build_via_vector_backend()
    namespace = via_namespace_for_bundle(bundle)
    session = bundle.get("session") or {}
    user_id = int(session.get("user_id") or 0)
    docs = []
    for item in _dedupe_refs(bundle.get("memory_refs") or [])[:24]:
        summary = _ref_text(item)
        if not summary:
            continue
        docs.append(
            {
                "id": _stable_id(namespace, item.get("memory_kind"), item.get("source_ref"), item.get("memory_key"), summary[:120]),
                "text": summary,
                "payload": _ref_payload(namespace, str(session.get("session_key") or ""), user_id, item, summary),
            }
        )
    try:
        count = await backend.upsert(namespace, docs)
    except Exception as exc:  # noqa: BLE001 - optional vector memory must not fail the request
        logger.warning("via.vector_memory.sync_failed", exc_info=True)
        count = 0
        status = {
            "ready": False,
            "error": _operation_error("vector_memory_sync", exc),
            "status": "partial",
            "reason": "vector_memory_sync_failed",
        }
    else:
        status = _vector_write_status(backend, requested=len(docs), upserted=count)
    return {
        "backend": getattr(backend, "backend_name", "none"),
        "namespace": namespace,
        "upserted": count,
        **status,
    }


async def recall_via_vector_memory(bundle: dict[str, Any], query_text: str, limit: int = VIA_VECTOR_TOP_K) -> list[dict[str, Any]]:
    backend = build_via_vector_backend()
    namespace = via_namespace_for_bundle(bundle)
    try:
        hits = await backend.search(namespace, query_text, max(1, int(limit)))
    except Exception:  # noqa: BLE001 - recall is optional; lexical/context paths remain available
        logger.warning("via.vector_memory.recall_failed", exc_info=True)
        return []
    if not isinstance(hits, list):
        logger.warning("via.vector_memory.invalid_recall_result")
        return []
    refs = []
    for hit in hits:
        if not isinstance(hit, dict):
            logger.warning("via.vector_memory.invalid_recall_hit")
            continue
        payload = hit.get("payload") or {}
        if not isinstance(payload, dict):
            logger.warning("via.vector_memory.invalid_recall_payload")
            continue
        summary = str(payload.get("summary") or "").strip()
        try:
            weight = float(hit.get("score") or 0.0)
        except (TypeError, ValueError):
            logger.warning("via.vector_memory.invalid_recall_score")
            continue
        refs.append({
            "memory_kind": "vector_recall",
            "source_ref": str(payload.get("source_ref") or hit.get("id") or ""),
            "memory_key": str(payload.get("memory_key") or ""),
            "weight": weight,
            "payload": {
                "summary": summary[:240],
                "text_snippet": str(payload.get("text_snippet") or "")[:600],
                "source": "vector_memory",
                "session_key": payload.get("session_key") or "",
                "payload_json": payload.get("payload_json") or "{}",
            },
        })
    return _dedupe_refs(refs)


async def store_via_vector_exchange(
    bundle: dict[str, Any],
    *,
    user_text: str,
    reply_text: str,
    signals: dict[str, Any] | None = None,
    current_surface: str = "upload",
) -> dict[str, Any]:
    backend = build_via_vector_backend()
    namespace = via_namespace_for_bundle(bundle)
    session = bundle.get("session") or {}
    persona = bundle.get("persona") or {}
    summary_error = ""
    try:
        summary_block = await summarize_via_exchange(
            user_text=user_text,
            reply_text=reply_text,
            signals=signals or {},
            current_surface=current_surface,
        )
        if not isinstance(summary_block, dict):
            raise ValueError("summary provider returned a non-object result")
    except Exception as exc:  # noqa: BLE001 - preserve the exchange with deterministic fallback text
        logger.warning("via.vector_memory.summary_failed", exc_info=True)
        summary_error = _operation_error("summary", exc)
        summary_block = {
            "summary": str((signals or {}).get("summary") or user_text or "").strip()[:180],
            "keywords": [
                str(item).strip()[:40]
                for item in list((signals or {}).get("keywords") or [])[:8]
                if str(item).strip()
            ],
            "provider": "fallback",
            "model": "",
        }
    text = _conversation_text(
        user_text,
        reply_text,
        summary_block.get("summary") or "",
        summary_block.get("keywords") or [],
        (signals or {}).get("traits") or {},
        current_surface,
    )
    source_ref = f"via-vector:{session.get('session_key')}:{_stable_id(user_text, reply_text)[:16]}"
    doc = {
        "id": _stable_id(namespace, source_ref),
        "text": text,
        "payload": {
            "namespace": namespace,
            "session_key": str(session.get("session_key") or ""),
            "user_id": int(session.get("user_id") or 0),
            "persona_key": str(persona.get("persona_key") or ""),
            "memory_kind": "conversation_signal",
            "memory_key": str(summary_block.get("summary") or "")[:120],
            "source_ref": source_ref,
            "summary": str(summary_block.get("summary") or "")[:300],
            "payload_json": json.dumps(
                {
                    "keywords": summary_block.get("keywords") or [],
                    "traits": (signals or {}).get("traits") or {},
                    "surface": current_surface,
                },
                ensure_ascii=False,
            )[:3000],
        },
    }
    try:
        upserted = await backend.upsert(namespace, [doc])
    except Exception as exc:  # noqa: BLE001
        logger.warning("via.vector_memory.exchange_upsert_failed", exc_info=True)
        upserted = 0
        vector_status = {
            "ready": False,
            "error": _operation_error("vector_exchange_upsert", exc),
            "status": "partial",
            "reason": "vector_exchange_upsert_failed",
        }
    else:
        vector_status = _vector_write_status(backend, requested=1, upserted=upserted)
    result = {
        "backend": getattr(backend, "backend_name", "none"),
        "namespace": namespace,
        "upserted": upserted,
        **vector_status,
        "summary": summary_block.get("summary") or "",
        "keywords": summary_block.get("keywords") or [],
        "provider": summary_block.get("provider") or "fallback",
        "model": summary_block.get("model") or "",
    }
    if summary_error:
        result["status"] = "partial"
        result["reason"] = "summary_provider_unavailable"
        result["summary_error"] = summary_error
    return result


async def store_via_seed_documents(bundle: dict[str, Any], items: list[dict[str, Any]]) -> dict[str, Any]:
    backend = build_via_vector_backend()
    namespace = via_namespace_for_bundle(bundle)
    session = bundle.get("session") or {}
    session_key = str(session.get("session_key") or "")
    user_id = int(session.get("user_id") or 0)
    docs = []
    for item in items:
        text = str(item.get("text") or "").strip()
        if not text:
            continue
        docs.append(
            {
                "id": _stable_id(
                    namespace,
                    item.get("memory_kind"),
                    item.get("source_ref"),
                    item.get("memory_key"),
                    text[:160],
                ),
                "text": text[:5000],
                "payload": _seed_payload(namespace, session_key, user_id, item),
            }
        )
    try:
        upserted = await backend.upsert(namespace, docs)
    except Exception as exc:  # noqa: BLE001
        logger.warning("via.vector_memory.seed_upsert_failed", exc_info=True)
        upserted = 0
        status = {
            "ready": False,
            "error": _operation_error("vector_seed_upsert", exc),
            "status": "partial",
            "reason": "vector_seed_upsert_failed",
        }
    else:
        status = _vector_write_status(backend, requested=len(docs), upserted=upserted)
    return {
        "backend": getattr(backend, "backend_name", "none"),
        "namespace": namespace,
        "upserted": upserted,
        **status,
    }
