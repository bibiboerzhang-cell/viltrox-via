def _response_json_object(response: httpx.Response, operation: str) -> dict[str, Any]:
    response.raise_for_status()
    try:
        data = response.json()
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{operation}: invalid JSON response") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{operation}: expected JSON object response")
    return data


def _operation_error(operation: str, exc: Exception) -> str:
    if isinstance(exc, httpx.HTTPStatusError):
        status_code = exc.response.status_code
        return f"{operation}: HTTP {status_code}"
    name = type(exc).__name__.lower()
    message = str(exc).lower()
    if "timeout" in name or "timeout" in message or "deadline" in message:
        return "embedding timeout" if operation == "embedding" else f"{operation}: timeout"
    if operation.startswith("qdrant_local") and "lock" in message:
        return f"{operation}: local store locked"
    # These ValueErrors are generated by the response validators above and contain
    # protocol state only. External exception text is never copied into responses.
    if isinstance(exc, ValueError) and str(exc).startswith(f"{operation}: "):
        return str(exc)[:300]
    return f"{operation}: unavailable"


def _qdrant_result(response: httpx.Response, operation: str) -> Any:
    data = _response_json_object(response, operation)
    if data.get("status") != "ok":
        raise ValueError(f"{operation}: Qdrant status is not ok")
    if "result" not in data:
        raise ValueError(f"{operation}: Qdrant response missing result")
    return data["result"]


def _validate_qdrant_collection(result: Any, operation: str, expected_dim: int | None = None) -> None:
    if not isinstance(result, dict):
        raise ValueError(f"{operation}: invalid Qdrant collection result")
    collection_status = str(result.get("status") or "").strip().lower()
    if collection_status not in {"green", "yellow", "grey"}:
        raise ValueError(f"{operation}: Qdrant collection status is {collection_status or 'missing'}")
    if expected_dim is None:
        return
    vector_config = (((result.get("config") or {}).get("params") or {}).get("vectors") or {})
    if not isinstance(vector_config, dict) or "size" not in vector_config:
        raise ValueError(f"{operation}: Qdrant collection vector size missing")
    try:
        actual_dim = int(vector_config["size"])
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{operation}: invalid Qdrant collection vector size") from exc
    if actual_dim != expected_dim:
        raise ValueError(f"{operation}: Qdrant vector size {actual_dim} does not match {expected_dim}")


def _validate_weaviate_class(data: dict[str, Any], operation: str) -> None:
    class_name = str(data.get("class") or "").strip()
    if class_name != WEAVIATE_CLASS:
        raise ValueError(f"{operation}: Weaviate class mismatch")


def _stable_id(*parts: Any) -> str:
    raw = "|".join(str(part or "").strip() for part in parts if str(part or "").strip())
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    return str(uuid.UUID(digest[:32]))


def via_namespace_for_bundle(bundle: dict[str, Any]) -> str:
    persona = bundle.get("persona") or {}
    session = bundle.get("session") or {}
    persona_key = str(persona.get("persona_key") or "").strip()
    if persona_key:
        return persona_key
    user_id = int(session.get("user_id") or persona.get("user_id") or 0)
    if user_id:
        return f"user:{user_id}:primary"
    session_key = str(session.get("session_key") or "").strip()
    return f"anon:{session_key or 'default'}"


def _ref_text(item: dict[str, Any]) -> str:
    payload = item.get("payload") or {}
    summary = str(payload.get("summary") or "").strip()
    if summary:
        return summary
    fact_value = payload.get("fact_value_json")
    if isinstance(fact_value, str) and fact_value.strip():
        return fact_value[:500]
    if isinstance(fact_value, (dict, list)):
        return json.dumps(fact_value, ensure_ascii=False)[:500]
    parts = [
        str(item.get("memory_kind") or "").strip(),
        str(item.get("memory_key") or "").strip(),
        str(item.get("source_ref") or "").strip(),
    ]
    return " | ".join(part for part in parts if part)[:300]


def _ref_payload(namespace: str, session_key: str, user_id: int, item: dict[str, Any], summary: str) -> dict[str, Any]:
    payload = item.get("payload") or {}
    return {
        "namespace": namespace,
        "session_key": session_key,
        "user_id": int(user_id or 0),
        "memory_kind": str(item.get("memory_kind") or "vector_memory"),
        "memory_key": str(item.get("memory_key") or ""),
        "source_ref": str(item.get("source_ref") or ""),
        "summary": summary[:300],
        "payload_json": json.dumps(payload, ensure_ascii=False)[:3000],
    }


def _conversation_text(user_text: str, reply_text: str, summary: str, keywords: list[str], traits: dict[str, Any], current_surface: str) -> str:
    parts = [
        f"summary: {summary}",
        f"user: {str(user_text or '').strip()}",
        f"reply: {str(reply_text or '').strip()}",
        f"keywords: {', '.join(keywords)}" if keywords else "",
        f"traits: {json.dumps(traits, ensure_ascii=False)}" if traits else "",
        f"surface: {current_surface}",
    ]
    return "\n".join(part for part in parts if part).strip()[:4000]


def _dedupe_refs(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    seen: set[tuple[str, str]] = set()
    out: list[dict[str, Any]] = []
    for item in items:
        key = (str(item.get("memory_kind") or ""), str(item.get("source_ref") or item.get("memory_key") or ""))
        if key in seen:
            continue
        seen.add(key)
        out.append(item)
    return out


def _seed_payload(
    namespace: str,
    session_key: str,
    user_id: int,
    item: dict[str, Any],
) -> dict[str, Any]:
    payload = dict(item.get("payload") or {})
    payload.update(
        {
            "namespace": namespace,
            "session_key": session_key,
            "user_id": int(user_id or 0),
            "memory_kind": str(item.get("memory_kind") or "seed_doc"),
            "memory_key": str(item.get("memory_key") or ""),
            "source_ref": str(item.get("source_ref") or ""),
            "summary": str(item.get("summary") or item.get("text") or "")[:300],
            "text_snippet": str(item.get("text") or payload.get("text_snippet") or "")[:1200],
            "payload_json": json.dumps(item.get("payload") or {}, ensure_ascii=False)[:3000],
        }
    )
    return payload


