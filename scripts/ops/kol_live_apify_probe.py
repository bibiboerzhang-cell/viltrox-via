"""Single, plan-bound public YouTube discovery probe; no inventory writes.

The caller owns approval and local DB selection. This module never provisions a
budget. Missing configured budgets/fences fail closed at the canonical boundary.
Official run API usageTotalUsd is an observed total that may arrive late; a
positive observation is not final billing. usageUsd is NOT a fallback total.
https://docs.apify.com/api/client/js/reference/interface/ActorRun
"""
